import { useState } from "react";
import { History } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog";
import type { SavedResult } from "@/lib/pdp/saved-results-store";

interface SavedResultsButtonProps {
  results: SavedResult[];
  /** Signed in with a permitted account; saved results are shared only then. */
  signedIn: boolean;
  loading: boolean;
  errors: string[];
  onOpen: (result: SavedResult) => void;
}

function formatDate(iso: string) {
  const date = new Date(iso);
  return Number.isNaN(date.getTime()) ? iso : date.toLocaleString();
}

/**
 * "View saved results (N)": every AI design run saved by anyone on the team. Opening one
 * shows it as generated — no AI key or tokens needed.
 */
export function SavedResultsButton({
  results,
  signedIn,
  loading,
  errors,
  onOpen,
}: SavedResultsButtonProps) {
  const [open, setOpen] = useState(false);
  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger asChild>
        <Button variant="outline" size="sm" disabled={!signedIn}>
          <History className="size-3.5" />
          {signedIn
            ? `View saved results (${loading ? "…" : results.length})`
            : "Sign in to view saved results"}
        </Button>
      </DialogTrigger>
      <DialogContent className="max-h-[85vh] max-w-2xl overflow-y-auto">
        <DialogHeader>
          <DialogTitle>Saved results</DialogTitle>
          <DialogDescription>
            AI designs generated by anyone on the team, with the IndiaMART product data they were
            made from. Opening one needs no AI key and uses no tokens.
          </DialogDescription>
        </DialogHeader>
        {errors.length > 0 && (
          <div
            role="alert"
            className="rounded-md border border-destructive/50 px-3 py-2 text-xs text-destructive"
          >
            {errors.map((e) => (
              <p key={e}>{e}</p>
            ))}
          </div>
        )}
        {results.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            No saved results yet. They are added automatically each time someone generates AI
            designs.
          </p>
        ) : (
          <ul className="space-y-2" aria-label="Saved results list">
            {results.map((result) => {
              const { data } = result;
              const names = data.products.map((p) => p.name.trim()).filter(Boolean);
              const aiCount = data.aiDesign.concepts.filter((c) => c.source === "ai").length;
              return (
                <li
                  key={result.id}
                  className="flex flex-wrap items-start justify-between gap-2 rounded-md border px-3 py-2 text-sm"
                >
                  <div className="min-w-0 flex-1">
                    <p className="font-medium">
                      {data.mcat || "MCAT not set"}
                      {data.mcatId && ` (MCAT ${data.mcatId})`}
                    </p>
                    <p className="truncate text-xs text-muted-foreground" title={names.join(", ")}>
                      {names.length > 0 ? names.join(" · ") : "No product names"}
                    </p>
                    <p className="text-xs text-muted-foreground">
                      {aiCount} AI design(s) by {data.aiDesign.model} ·{" "}
                      {data.aiDesign.benchmarkPages} benchmark page(s) ·{" "}
                      {formatDate(result.createdAt)} · {result.createdBy}
                    </p>
                  </div>
                  <Button
                    size="sm"
                    aria-label={`Open saved result for ${data.mcat || "MCAT"} from ${formatDate(result.createdAt)}`}
                    onClick={() => {
                      onOpen(result);
                      setOpen(false);
                    }}
                  >
                    Open
                  </Button>
                </li>
              );
            })}
          </ul>
        )}
      </DialogContent>
    </Dialog>
  );
}
